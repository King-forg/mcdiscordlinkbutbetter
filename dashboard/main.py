class _Colors:
    class Fore:
        RED = "\033[31m"
        GREEN = "\033[32m"
        YELLOW = "\033[33m"

    class Back:
        RED = "\033[41m"
        GREEN = "\033[42m"
        YELLOW = "\033[43m"

    class Style:
        BRIGHT = "\033[1m"
        RESET_ALL = "\033[0m"


colorama = _Colors()
Fore = colorama.Fore
